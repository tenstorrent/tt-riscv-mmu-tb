"""Regression generator + runner for the MMU UVM testbench.

Single entry point for two jobs:

  1. GENERATE a regression.yaml from a (simulator x test x seed) matrix.
  2. RUN a regression.yaml — a target DAG executed locally (thread pool) or
     through an arbitrary job-submit wrapper (LSF/SLURM/...).

No dependency on any proprietary tooling; Python 3.6+, stdlib only (PyYAML is
used when installed, otherwise a built-in minimal parser handles the yaml we
generate).

Usage:
    runreg.py                            # generate only -> regress/regression.yaml
    runreg.py --random -n 10             # 10 random seeds per test
    runreg.py --run -j 8                 # generate, then run locally
    runreg.py --random -n 10 --run -j 8 --submit 'bsub -q myqueue -I'
    runreg.py regress/nightly.yaml -j 8  # run an EXISTING yaml
    runreg.py --clean --keep 2           # remove old regression output

regression.yaml schema (subset):

    config:                 # optional, informational
      project: mmu
      owners: alice

    build_mmu_tb_vcs:
      command: "make -C /path compile SIM=vcs"

    test_vcs_mmu_ifu_test_s1:
      command: "make -C /path run-only SIM=vcs TEST=mmu_ifu_test PT_SEED=1"
      deps: [build_mmu_tb_vcs]
      ignore_failed_deps: false   # optional

Targets run once all their deps have succeeded. A target whose dep failed is
SKIPPED (unless ignore_failed_deps: true). Exit status is non-zero if any
target failed or was skipped.
"""

import argparse
